/***************************************************
 * 9) FRACTAL VISUALIZATION (canvas0)
 ***************************************************/
let angle0 = 0, colorOffset0 = 0;
function drawFractal() {
  frameId0 = requestAnimationFrame(drawFractal);
  if (!isVis0Running) return;
  if (!analyser || !dataArray) return; // no track playing yet

  ctx0.clearRect(0, 0, canvas0.width, canvas0.height);
  analyser.getByteFrequencyData(dataArray);

  const avgAmp = dataArray.reduce((a, b) => a + b, 0) / bufferLength;
  const maxAmp = Math.max(...dataArray);
  const normMax = maxAmp / 255;

  const cx = canvas0.width / 2;
  const cy = canvas0.height / 2;
  ctx0.save();
  ctx0.translate(cx, cy);

  const totalSpirals = 20;
  const angleBetweenSpirals = (spiralSpreadFactor * Math.PI) / totalSpirals;

  for (let j = 0; j < totalSpirals; j++) {
    const isMirrored = j >= totalSpirals / 2;
    const spiralBaseAngle = j * angleBetweenSpirals;

    for (let i = 0; i < 360; i += 5) {
      const fraction = i / 360;
      const rad = fraction * 200 + (avgAmp / 255) * 150;
      const sign = isMirrored ? -1 : 1;
      const shapeRotation = spiralBaseAngle + sign * (angle0 + i) * (Math.PI / 180);

      ctx0.save();
      ctx0.rotate(shapeRotation);

      const hue = (i + colorOffset0 + avgAmp * 2 + j * 18) % 360;
      const saturation = 50 + (avgAmp / 255) * 50;
      ctx0.fillStyle = `hsl(${hue}, ${saturation}%, 50%)`;

      const rectSize = 10 * shapeSizeFactor;
      ctx0.fillRect(rad, rad * 0.01, rectSize, rectSize);
      ctx0.restore();
    }
  }
  ctx0.restore();

  angle0 += spinSpeed * (0.2 + normMax);
  colorOffset0 += 0.9 + avgAmp / 255;
}

/***************************************************
 * 10) VISUALIZATION #1 (canvas1)
 ***************************************************/
let angle1Val = 0, colorOffset1Val = 0;

function drawVisualization1() {
    frameId1 = requestAnimationFrame(drawVisualization1);
    if (!isVis1Running) return;
    if (!analyser || !dataArray) return;

    ctx1.clearRect(0, 0, canvas1.width, canvas1.height);
    analyser.getByteFrequencyData(dataArray);

    const avgAmp = dataArray.reduce((a, b) => a + b, 0) / bufferLength;
    const maxAmp = Math.max(...dataArray);
    const normMax = maxAmp / 255;

    const centerX = canvas1.width / 2;
    const centerY = canvas1.height / 2;
    ctx1.save();
    ctx1.translate(centerX, centerY);

    const totalSpirals = 20;
    const angleBetweenSpirals = (spiralSpreadFactor1 * Math.PI) / totalSpirals;

    for (let i = 0; i < totalSpirals; i++) {
        ctx1.save();
        ctx1.rotate(i * angleBetweenSpirals + angle1Val);

        for (let j = 0; j < 360; j += 10) {
            const isMirrored = j >= totalSpirals / 2; // Half are mirrored
            const spiralBaseAngle = j * angleBetweenSpirals;
            const radius = j + avgAmp;
            const x = radius * Math.cos((j * Math.PI) / 180);
            const y = radius * Math.sin((j * Math.PI) / 180);

            // Apply uneven mirroring using -2 and 2
            const sign = isMirrored ? -2 : 2;

            // Warped shape rotation for a distorted effect
            const shapeRotation = spiralBaseAngle + sign * (angle1Val + i) * (Math.PI / 180);
            ctx1.save();
            ctx1.rotate(shapeRotation);

            // Dynamic shape sizing
            const shapeSize = (avgAmp / 10) * shapeSizeFactor1;

            // Color shifting for dynamic visuals
            const hue = (j + colorOffset1Val) % 360;
            ctx1.fillStyle = `hsl(${hue}, 100%, 50%)`;

            if (maxAmp > 250) {
                drawShape(ctx1, x, y, shapeSize, 'triangle');
            } else if (maxAmp > 170) {
                drawShape(ctx1, x, y, shapeSize, 'square');
            } else if (maxAmp > 120) {
                drawShape(ctx1, x, y, shapeSize, 'circle');
            } else {
                ctx1.fillRect(x, y, 3 * shapeSizeFactor1, 3 * shapeSizeFactor1);
            }

            ctx1.restore();
        }
        ctx1.restore();
    }
    ctx1.restore();

    // Update Animation Values
    const amplitudeFactor = normMax * 0.1;
    angle1Val += spinSpeed1 * amplitudeFactor;
    colorOffset1Val += 0.9 + avgAmp / 255;
}

// Shape Drawing Function
function drawShape(ctx, x, y, size, shape) {
    ctx.beginPath();
    switch (shape) {
        case 'circle':
            ctx.arc(x, y, size, 0, 8 * Math.PI);
            break;
        case 'square':
            ctx.rect(x - size / 20, y - size / 20, size, size);
            break;
        case 'triangle':
            ctx.moveTo(x, y - size);
            ctx.lineTo(x - size, y + size);
            ctx.lineTo(x + size, y + size);
            ctx.closePath();
            break;
    }
    ctx.fill();
}

