let audioContext = null;
let analyser = null;
let dataArray = null;
let bufferLength = 0;

/***************************************************
 * 3) Vue App (Music Library)
 ***************************************************/
new Vue({
  el: '#media-list',
  data: {
    title: 'FOOD4THOTH Visualiser Music Library',
    mediaList: mediaData,
    album: '',
    currentlyPlaying: null,
    currentAudioElement: null,
  },
  methods: {
    toggleDetails(media) {
      media.showDetails = !media.showDetails;
    },
    filterList(event) {
      this.album = event.target.value;
    },

    /**
     * Called on the @play event of the <audio> element.
     * This is where we attach the <audio> to the Analyser, but ONLY ONCE.
     */
    playAudio(media, event) {
      const audioEl = event.target;

      // If a different track was playing, stop it:
      if (this.currentAudioElement && this.currentAudioElement !== audioEl) {
        this.currentAudioElement.pause();
        this.currentAudioElement.currentTime = 0;
      }

      // Update the "currently playing" track
      this.currentlyPlaying = media;
      this.currentAudioElement = audioEl;

      // Ensure global AudioContext + Analyser exist
      if (!audioContext) {
        audioContext = new (window.AudioContext || window.webkitAudioContext)();
      }
      if (!analyser) {
        analyser = audioContext.createAnalyser();
        analyser.fftSize = 256;
        bufferLength = analyser.frequencyBinCount;
        dataArray = new Uint8Array(bufferLength);
      }

      // ---- FIX: only create the source node ONCE per audioEl
      if (!audioEl._alreadyConnected) {
        const trackSource = audioContext.createMediaElementSource(audioEl);
        trackSource.connect(analyser);
        analyser.connect(audioContext.destination);

        audioEl._alreadyConnected = true; // Mark so we don't re-create again
      }
      // ----

      // Resume if audioContext is suspended (e.g. iOS)
      if (audioContext.state === 'suspended') {
        audioContext.resume();
      }

      // Start the visual loops if not running
      startVisuals();

      // When the track ends, reset
      audioEl.onended = () => {
        this.currentlyPlaying = null;
        // Optionally disconnect, if desired
        // But usually you can just leave it connected
      };
    },
  },
  computed: {
    uniqueAlbumsList() {
      const albums = new Set(this.mediaList.map(item => item.album));
      return Array.from(albums);
    },
    filteredMediaList() {
      if (this.album) {
        return this.mediaList.filter(item => item.album === this.album);
      }
      return this.mediaList;
    },
  },
});

